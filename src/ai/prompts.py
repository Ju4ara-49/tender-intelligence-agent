def build_user_prompt(tender_text: str, ai_context: str) -> str:
    """Формирует запрос AI для анализа конкретного тендера."""

    context_block = ""

    if ai_context:
        context_block = (
            "\n\n"
            "=== КОНТЕКСТ ЗАКАЗЧИКА ===\n"
            "Это реальные требования пользователя. "
            "Используй их как главный критерий оценки.\n\n"
            f"{ai_context}\n"
            "=== КОНЕЦ КОНТЕКСТА ЗАКАЗЧИКА ===\n"
        )

    return (
        "Проанализируй следующий тендер.\n\n"
        "ВАЖНО: сначала определи РЕАЛЬНЫЙ ПРЕДМЕТ ЗАКУПКИ, "
        "а затем сравни его с требованиями пользователя. "
        "Не ориентируйся только на отдельные совпавшие слова.\n"
        f"{context_block}\n"
        "=== ДАННЫЕ ТЕНДЕРА ===\n"
        f"{tender_text}\n"
        "=== КОНЕЦ ДАННЫХ ТЕНДЕРА ===\n\n"
        "Верни только требуемый JSON."
    )
